// Function to calculate the area of a square
function areaOfSquare(sideLength) {
    // Calculate the area of a square given the length of its side
    var area = sideLength * sideLength;
    // Return the calculated area
    return area;
}

// Example usage of the areaOfSquare function
var area = areaOfSquare(5);
// Output the area of the square
console.log("The area of the square is: " + area);